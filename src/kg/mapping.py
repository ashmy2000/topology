"""How a ServiceNow extract becomes the graph. The loader reads this config; main() writes mappings/servicenow.md.

Run kg/pdi.py first: main() lists the relationship types found in the extract.
"""
import json
from collections import Counter
from pathlib import Path

from kg.pdi import OUT_DIR

DOC = Path(__file__).resolve().parents[2] / 'mappings' / 'servicenow.md'

# table -> node label; CI tables (one file per class in out/pdi/ci/) all become :CI plus one label per class level
NODE_TABLES = {'sys_user_group': 'Group', 'sys_user': 'Person', 'cmn_location': 'Location', 'incident': 'Incident',
               'em_alert': 'Alert'}
# fields kept on these nodes; on the others every filled field is kept. sys_user also holds passwords.
NODE_FIELDS = {'sys_user': ['sys_id', 'name', 'user_name', 'email', 'active'],
               'sys_user_group': ['sys_id', 'name', 'email', 'active'],
               'cmn_location': ['sys_id', 'name', 'full_name', 'city', 'country']}

# reference field -> (relationship type, target label), per table; 'cmdb_ci' means every CI class.
# Other reference fields stay a property holding the name they point to.
REFERENCES = {
    'cmdb_ci': {'support_group': ('SUPPORT_GROUP', 'Group'), 'assignment_group': ('ASSIGNMENT_GROUP', 'Group'),
                'managed_by_group': ('MANAGED_BY_GROUP', 'Group'), 'managed_by': ('MANAGED_BY', 'Person'),
                'owned_by': ('OWNED_BY', 'Person'), 'it_application_owner': ('IT_APPLICATION_OWNER', 'Person'),
                'location': ('LOCATED_AT', 'Location'),
                # hosting recorded only in a field: 14 Windows cluster nodes and 5 MySQL databases have no relationship row
                'server': ('HOSTED_ON', 'CI'), 'db_server': ('HOSTED_ON', 'CI')},
    'cmn_location': {'parent': ('PART_OF', 'Location')},
    'incident': {'cmdb_ci': ('AFFECTS', 'CI'), 'assignment_group': ('ASSIGNMENT_GROUP', 'Group')},
    'em_alert': {'cmdb_ci': ('ON', 'CI'), 'parent': ('GROUPED_UNDER', 'Alert'), 'incident': ('RAISED', 'Incident'),
                 'assignment_group': ('ASSIGNMENT_GROUP', 'Group')},
}

# relationship table -> (parent field, child field, child label); the type is named after the parent descriptor
RELATIONSHIP_TABLES = {'cmdb_rel_ci': ('parent', 'child', 'CI'), 'cmdb_rel_person': ('ci', 'user', 'Person'),
                       'cmdb_rel_group': ('ci', 'group', 'Group')}
# the four location types become one LOCATED_IN (thing -> place); sn_type keeps the original name
LOCATION_TYPES = {'In Rack::Rack contains', 'Located in::Houses', 'Located In::Contains Room',
                  'Located in Zone::Zone contains'}
# bigger place = higher rank; a location row whose parent outranks its child is recorded backwards and is flipped
PLACE_RANK = {'Rack': 1, 'DataCenterZone': 2, 'ComputerRoom': 3, 'DataCenter': 4}

# an outage travels against the arrow of these types (the parent needs the child)
WALKED = ['CONNECTED_BY', 'CONNECTS_TO', 'DEPENDS_ON', 'HOSTED_ON', 'LOCATED_IN', 'RUNS_ON']
# these carry an outage only through a rule: a cluster when all members are down; a business application through
# the services it consumes, where losing only the DR copy puts it at risk, not down
GATED = {'MEMBERS': 'cluster down when every member is down', 'CONSUMES': 'business application rule'}

HEAD = """# ServiceNow -> graph mapping

Generated by `kg/mapping.py` from the loader config; do not edit by hand.

## Nodes

| ServiceNow table | Graph node | Fields kept |
|---|---|---|
| `cmdb_ci_*` (one table per class) | `:CI` plus one label per class level (from `sys_db_object`) | every filled field |"""
VALUES = """
## Values

- Empty field: no property.
- Date-time `value` (UTC): Neo4j datetime. `true`/`false`: boolean. A number whose label is the same number with
  thousands separators: integer or float.
- A code whose label differs (choice fields such as `install_status` 1 / Installed): the code, plus `<field>_label`.
- A mapped reference whose target is not in the extract: no relationship; `<field>_sys_id` and `dangling_refs` on
  the node.
- Provenance on every node and relationship: `src_system`, `src_instance`, `extracted_at` (from `manifest.json`),
  `src_table`, `load_run`; relationships also `src_sys_id` (the row or record holding the link) and, for reference
  fields, `src_field`."""


def graph_type(sn_type):
    """'Depends on::Used by' -> DEPENDS_ON; the four location types -> LOCATED_IN."""
    if sn_type in LOCATION_TYPES:
        return 'LOCATED_IN'
    return sn_type.split('::')[0].upper().replace(' ', '_')


def outage_role(graph_type_name):
    if graph_type_name in WALKED:
        return 'walked'
    return GATED.get(graph_type_name, 'loaded, not walked')


def main():
    lines = HEAD.splitlines()
    lines += [f"| `{table}` | `:{label}` | {', '.join(NODE_FIELDS.get(table, ['every filled field']))} |"
              for table, label in NODE_TABLES.items()]
    lines += ['', '## Reference fields that become relationships', '',
              '| ServiceNow table.field | Graph relationship |', '|---|---|']
    for table, fields in REFERENCES.items():
        source = 'CI' if 'cmdb_ci' == table else NODE_TABLES[table]
        lines += [f'| `{table}.{field}` | `(:{source})-[:{rel}]->(:{target})` |'
                  for field, (rel, target) in fields.items()]
    lines += ['', '## Relationship types in this extract', '',
              '| ServiceNow table | ServiceNow type | Rows | Graph type | Outage |', '|---|---|---|---|---|']
    for table in RELATIONSHIP_TABLES:
        counts = Counter(row['type']['display_value'] for row in json.loads((OUT_DIR / f'{table}.json').read_text()))
        lines += [f'| `{table}` | {sn_type} | {n} | `{graph_type(sn_type)}` | {outage_role(graph_type(sn_type))} |'
                  for sn_type, n in sorted(counts.items())]
    lines += VALUES.splitlines()
    DOC.parent.mkdir(exist_ok=True)
    DOC.write_text('\n'.join(lines) + '\n')
    print(f'{DOC}: {len(lines)} lines')


if '__main__' == __name__:
    main()
